# Training function
def single_iteration(lpn_model, train_xx, true_f, i, bsize, optimizer, p, loss_type = 2, gamma_loss=None):
    """
    Input: 
        lpn_model --- pre-defined LPN model;
        train_xx --- data tensor for training this iteration;
        true_f --- true output tensor for training validation;
        i --- index of iteration;
        bsize --- batch size;
        optimizer --- optimizer;
        loss_type --- type of loss functions: L1, L2 (default) and L_eq31;
    """
    
    
    f_xx, xx = true_f.to(device), train_xx.to(device)
    
    f_out = lpn_model(xx)
    cvx_out = lpn_model.scalar(xx)  # cvx_out is the output psi of the LPN.

    if loss_type == 2:
        loss = (f_out - f_xx).pow(2).sum() / bsize  # MSE loss
        loss_mse = (f_out - f_out).pow(2).sum() / bsize
    elif loss_type == 1:
        loss = (f_out - f_xx).abs().sum() / bsize  # MAE loss
    # elif loss_type == 0:
    #     loss = exp_func(f_out - f_xx, gamma_loss).mean()  # proximal matching loss
    # elif loss_type == -1:   # loss induced by (3.1)

        # # R(f(y)) = y^T f(y) - 1/2 * ||f(y)||_2^2 - psi(y)
        # # Recall the R is the ||x|| - log(1/2)
        # # LHS = xx.abs() - torch.log(torch.tensor(1/2))
        # # RHS = xx * f_out - 0.5 * (f_out ** 2) - cvx_out
        # if ex == 1:   # Example 1, R is L1 norm.
        #     LHS = torch.norm(f_out, p = 1, dim = 1)
        #     RHS = torch.diag(xx @ f_out.T) - 0.5 * torch.sum(f_out ** 2, dim = 1) - cvx_out.squeeze(-1)
        # if ex == 2:   # Example 2, R is q function.
        #     LHS = 1/2 * torch.sum(f_out ** 2, dim = 1)
        #     RHS = torch.diag(xx @ f_out.T) - 0.5 * torch.sum(f_out ** 2, dim = 1) - cvx_out.squeeze(-1)
        # loss = 0.5 * (LHS - RHS).pow(2).sum()
        # loss_mse = (f_out - f_xx).pow(2).sum() / bsize  # MSE loss
    else:
        raise ValueError("loss_type must be -1, 0, 1, or 2")
        
    optimizer.zero_grad()
    loss.backward()
    optimizer.step()
    if i % 500 == 0:
        if loss_type == -1:
            print("l_eq31:", loss.item())
            print("mse for eq31", loss_mse.item())
        if loss_type == 2:
            print("mse:", loss.item())

    lpn_model.wclip()
    return loss, loss_mse

# Function to plot learned prox, convex function, original function
def plot_L21(plot_data, model):
    """
    input:
        plot_data for plot --- plot_amount, N, by p;
            So training with plot_amount (N ,p) data tensors, and plot 
            plot_amount * N vectors in p dim. (p == 2)
        model --- trained LPN model;
    
    return: 
    
    """

    # # lb = -4  # Lower bound of the box
    # # ub = 4   # Upper bound of the box
    # # points_per_dim = 50  # Number of points per dimension
    # xi = torch.tensor(linspace_gen(p, lb, ub, points_per_dim))
    
    xi = plot_data['xx']   # dimension amount by p by N
    true_y = plot_data['f_xx']     # dimension amount by p by N
    
    amount_dt, p, N = xi.shape
    
    if p > 2 or p < 2:
        raise ValueError("Dimension not equal to 2")
        return 0
    
    
    # run the model.
    y = model(xi)   # dimension amount by p by N
    c = model.scalar(xi)   # dimension amount by N
    
    # plot results
    vis_y = y.permute(1, 0, 2).reshape(p, amount_dt * N)
    vis_true_y = true_y.permute(1, 0, 2).reshape(p, amount_dt * N)
    
    # Scatter plot to compare the scatter plots.    

    plt.rcParams["figure.figsize"] = (8, 6)
    plt.plot(vis_y[0, :].detach().numpy(), vis_y[1, :].detach().numpy(), '*', color = 'blue', label = 'LPN')    
    plt.plot(vis_true_y[0, :].detach().numpy(), vis_true_y[1, :].detach().numpy(), 'o', markerfacecolor='none', markeredgecolor='red', markersize=8, label = 'ADMM (true)') 
    plt.title("Learned prox by LPN")
    plt.legend()
    plt.show()
    
    # print the loss on the plot case.
    loss = (y - true_y).pow(2).sum() / bsize  # MSE loss
    print("mse for the plot:", loss.detach().numpy())

