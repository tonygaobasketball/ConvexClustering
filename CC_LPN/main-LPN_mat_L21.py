"""
LPN for proximal operator.

---
Consider function g

g: R^{p by n} ---> R
g(X) = ||X Y^T||_{2,1}, 
where  Y \in R^{m by n} is given.

Define functional f: R^{p by n} ---> R^{p by n}
as the proximal operator of g:

f = prox_g

---
Training and testing data: 
    (X_i, f_i), 
    1) X_i's are generated by L21_data_gen in Funcs.py
    2) f_i's are f_i = prox_g(X_i), calculated by ADMM in Funcs.py.
    

The lpn_model in this code is to approximate the proximal operator.
Let H be the trained lpn_model, and for each testing point X_i,
 H(X_i) = \hat f_i.

Loss calculated between the testing f_i's and the \hat f_i's.
(default loss function is MSE: "loss_type = 2").
"""

#%% Utilities
